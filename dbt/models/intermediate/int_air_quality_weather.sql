select
    o.location_id,
    o.location_name,
    o.sensor_id,
    o.parameter,
    o.parameter_id,
    o.unit,
    o.value,
    o.period_label,
    o.period_interval,
    o.datetime_from_utc,
    o.datetime_to_utc,
    o.datetime_from_local,
    o.datetime_to_local,
    o.measurement_date_utc,
    o.latitude,
    o.longitude,
    o.source,
    o.source_file,
    o.retrieval_datetime_from,
    o.retrieval_datetime_to,
    o.weather_hour_utc,
    o.temperature_2m_c,
    o.relative_humidity_2m_pct,
    o.precipitation_mm,
    o.wind_speed_10m_kmh,
    o.weather_source,
    o.weather_latitude,
    o.weather_longitude,
    l.location_name as canonical_location_name,
    l.latitude as canonical_latitude,
    l.longitude as canonical_longitude,
    o.weather_source is not null as has_weather_context
from {{ ref('stg_observations') }} as o
left join {{ ref('stg_locations') }} as l
    on o.location_id = l.location_id
